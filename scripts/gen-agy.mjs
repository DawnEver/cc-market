#!/usr/bin/env node
// gen-agy.mjs — Generate Antigravity (agy) plugin artifacts from the Claude-Code source of truth.
//
// Sibling of gen-codex.mjs, same discipline: the outputs are generated AND committed, and
// tests/gen-agy.test.mjs fails when they drift from the sources. Per plugin listed in
// `.claude-plugin/marketplace.json`:
//   - `.antigravity-plugin/plugin.json`  agy manifest (name, version, author, homepage,
//                                        repository, `disabled` for dormant plugins, `skills`)
//   - `hooks.json` (plugin ROOT)         agy named-hook format; agy only reads the root file for
//                                        native plugins. Commands run in the plugin folder, so they
//                                        are relative and carry `--host agy` for the shared helpers.
//   - `mcp_config.json`                  the `.mcp.json` servers with relative paths
//   - `agy-skills/<name>/SKILL.md`       one skill per Claude slash command: agy plugins have no
//                                        commands. agy-only (declared via manifest `skills`), so
//                                        Claude Code and Codex never see duplicates.
//   - `agents/<name>.md`                 when a plugin authors Claude-tier agents in
//                                        `claude-agents/` (and declares `"agents": [...]` in
//                                        `.claude-plugin/plugin.json` so Claude Code loads only
//                                        `claude-agents/`), generates agy-compatible `agents/*.md`
//                                        with Claude model tiers mapped (`haiku->flash`,
//                                        `sonnet->inherit`, `opus->pro`), because agy always
//                                        auto-scans `./agents/*.md` (it ignores any manifest
//                                        `agents` key) and rejects Claude model shorthands.
//
// Event mapping (Claude → agy): PreToolUse/PostToolUse keep their name with tool matchers
// translated (shared/hook-facts.mjs CLAUDE_TO_AGY_TOOLS); UserPromptSubmit → PreInvocation (the
// handler acts only on the turn's first invocation); SessionStart, Stop unchanged; PostCompact
// dropped (agy has no compaction event). Anything else is an error until mapped here.

import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '../shared/lib.mjs';
import { CLAUDE_TO_AGY_TOOLS } from '../shared/hook-facts.mjs';

export const GENERATED_MARK = 'GENERATED by scripts/gen-agy.mjs — do not edit; edit the Claude source and re-run.';
// Plugins that ship switched off on agy (dormant in this marketplace's own setup too).
export const AGY_DISABLED = new Set(['watch', 'cc-academia']);
const AGY_SKILLS_DIR = 'agy-skills';
const CLAUDE_AGENTS_DIR = 'claude-agents';
const MATCHED_EVENTS = new Set(['PreToolUse', 'PostToolUse']);
export const EVENT_MAP = {
  PreToolUse: 'PreToolUse', PostToolUse: 'PostToolUse', SessionStart: 'SessionStart',
  UserPromptSubmit: 'PreInvocation', Stop: 'Stop', PostCompact: null,
};

// Claude model tier shorthands -> agy's accepted subagent model tiers (`inherit|flash_lite|flash|pro`).
export const AGENT_MODEL_MAP = Object.freeze({
  haiku: 'flash',
  sonnet: 'inherit',
  opus: 'pro',
  inherit: 'inherit',
  flash_lite: 'flash_lite',
  flash: 'flash',
  pro: 'pro',
});

/** Translate a Claude matcher ("Write|Edit|Bash") to agy tool names; null when nothing maps. */
export function translateMatcher(matcher) {
  if (matcher === undefined || matcher === '' || matcher === '*') return matcher ?? '*';
  const out = [];
  for (const name of String(matcher).split('|').map(s => s.trim()).filter(Boolean)) {
    const mapped = CLAUDE_TO_AGY_TOOLS[name];
    if (!mapped) throw new Error(`no agy tool mapping for matcher tool ${JSON.stringify(name)}`);
    for (const m of mapped) if (!out.includes(m)) out.push(m);
  }
  return out.length ? out.join('|') : null;
}

/** `node "${CLAUDE_PLUGIN_ROOT}/hooks/x.js"` → `node ./hooks/x.js --host agy`. */
export function translateCommand(command) {
  const rel = String(command)
    .replace(/"\$\{(?:CLAUDE_)?PLUGIN_ROOT\}[\\/]([^"]+)"/g, './$1')
    .replace(/\$\{(?:CLAUDE_)?PLUGIN_ROOT\}[\\/]/g, './');
  if (/\$\{(?:CLAUDE_)?PLUGIN_ROOT\}/.test(rel)) throw new Error(`cannot relativize hook command: ${command}`);
  return /\s--host\s+agy\b/.test(rel) ? rel : `${rel} --host agy`;
}

function translateHandler(h) {
  const out = { type: 'command', command: translateCommand(h.command) };
  if (h.timeout !== undefined) out.timeout = h.timeout;
  return out;
}

/** Claude `hooks/hooks.json` object → agy root hooks.json (one named hook per plugin). */
export function transpileHooks(name, claudeHooks) {
  const spec = {};
  for (const [event, groups] of Object.entries(claudeHooks.hooks || {})) {
    if (!(event in EVENT_MAP)) throw new Error(`${name}: hook event ${event} has no agy mapping`);
    const target = EVENT_MAP[event];
    if (!target) continue;
    for (const group of groups) {
      const handlers = (group.hooks || []).map(translateHandler);
      if (!handlers.length) continue;
      if (MATCHED_EVENTS.has(target)) {
        const matcher = translateMatcher(group.matcher);
        if (matcher === null) continue;
        (spec[target] ??= []).push({ matcher, hooks: handlers });
      } else {
        (spec[target] ??= []).push(...handlers);
      }
    }
  }
  return Object.keys(spec).length ? { [name]: spec } : null;
}

function normalizePluginRootPath(value) {
  if (/^\$\{(?:CLAUDE_)?PLUGIN_ROOT\}$/.test(value)) return '.';
  const prefix = /^\$\{(?:CLAUDE_)?PLUGIN_ROOT\}[\\/]/;
  return prefix.test(value) ? `./${value.replace(prefix, '').replaceAll('\\', '/')}` : value;
}

function normalizeMcpValue(value) {
  if (typeof value === 'string') return normalizePluginRootPath(value);
  if (Array.isArray(value)) return value.map(normalizeMcpValue);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, normalizeMcpValue(v)]));
  }
  return value;
}

/** `.mcp.json` → agy `mcp_config.json` (relative paths; agy runs plugin servers from the plugin). */
export function transpileMcp(mcp) {
  const out = normalizeMcpValue(mcp);
  for (const server of Object.values(out.mcpServers || {})) {
    if (server && typeof server === 'object' && server.command && server.cwd === undefined) server.cwd = '.';
  }
  return out;
}

/** The agy manifest. */
export function transpileManifest(manifest, entry = {}) {
  const repo = entry.repository || manifest.repository || 'https://github.com/DawnEver/cc-market';
  const out = { name: manifest.name };
  if (manifest.version) out.version = manifest.version;
  if (manifest.description) out.description = manifest.description;
  if (manifest.author) out.author = manifest.author;
  out.homepage = manifest.homepage || `${repo.replace(/\.git$/, '')}/tree/main/${manifest.name}`;
  out.repository = repo;
  if (AGY_DISABLED.has(manifest.name)) out.disabled = true;
  return out;
}

// ── Agent model-tier transpilation (`claude-agents/` → `agents/`) ──

/** Transpile a `claude-agents/*.md` definition into an agy-valid `agents/*.md` file. */
export function transpileAgent(text, sourceLabel = 'agent') {
  const normalized = text.replace(/\r\n/g, '\n');
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(normalized);
  if (!m) return normalized;
  const fmLines = m[1].split('\n').map(line => {
    const kv = /^(model:\s*)(["']?)([^"'\s#]+)\2(\s*(?:#.*)?)$/.exec(line);
    if (!kv) return line;
    const raw = kv[3].toLowerCase();
    const mapped = AGENT_MODEL_MAP[raw];
    if (!mapped) throw new Error(`${sourceLabel}: agent model ${JSON.stringify(kv[3])} has no agy tier mapping`);
    return `${kv[1]}${mapped}${kv[4]}`;
  });
  const body = normalized.slice(m[0].length).replace(/^\n+/, '');
  return `---\n${fmLines.join('\n')}\n---\n\n<!-- ${GENERATED_MARK} -->\n\n${body}`;
}

// ── Command → skill wrappers ──

function parseFrontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!m) return { meta: {}, body: text };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
  }
  return { meta, body: text.slice(m[0].length) };
}

function listCommandFiles(dir, prefix = []) {
  const out = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...listCommandFiles(full, [...prefix, entry]));
    else if (entry.endsWith('.md')) out.push({ full, parts: [...prefix, entry.slice(0, -3)] });
  }
  return out;
}

/** Where a plugin's Claude commands live (manifest `commands` paths, else `commands/`). */
export function commandFiles(pluginDir, manifest) {
  const roots = Array.isArray(manifest.commands) ? manifest.commands
    : typeof manifest.commands === 'string' ? [manifest.commands] : ['./commands'];
  const files = [];
  for (const r of roots) {
    const p = join(pluginDir, r);
    if (!existsSync(p)) continue;
    if (statSync(p).isDirectory()) files.push(...listCommandFiles(p));
    else files.push({ full: p, parts: [r.split('/').at(-1).replace(/\.md$/, '')] });
  }
  return files;
}

const yamlString = s => JSON.stringify(String(s));

/** One SKILL.md wrapping a Claude slash command for agy. */
export function commandSkill(plugin, skillName, parts, text) {
  const { meta, body } = parseFrontmatter(text);
  const slash = `/${plugin}:${parts.join(':')}`;
  const description = `${meta.description || `The ${slash} command`} (Antigravity port of the Claude Code ${slash} command; use when the user asks for ${slash} or "${parts.join(' ')}".)`;
  return [
    '---',
    `name: ${skillName}`,
    `description: ${yamlString(description)}`,
    '---',
    '',
    `<!-- ${GENERATED_MARK} -->`,
    '',
    `# ${slash} (Antigravity port)`,
    '',
    `This skill is the \`${slash}\` slash command of the \`${plugin}\` plugin. Antigravity plugins have`,
    'no slash commands, so perform the command below yourself:',
    '',
    `- **Arguments**: \`$ARGUMENTS\` stands for whatever the user wrote after the command${meta['argument-hint'] ? ` (expected: \`${meta['argument-hint']}\`)` : ''}. Ask if it is missing and required.`,
    '- **Plugin root**: `${CLAUDE_PLUGIN_ROOT}` is this plugin\'s directory — two levels above this SKILL.md.',
    '- **Inline shell**: a line of the form !`<command>` is a shell command — run it with `run_command`',
    '  (arguments and plugin root substituted) and treat its output as if it stood in its place.',
    '- **Subagents**: where the command dispatches an agent or the Task tool, use `invoke_subagent`;',
    '  this plugin\'s agents are loaded from its `agents/` directory.',
    meta['disable-model-invocation'] === 'true'
      ? `- **User-only**: in Claude Code only the user may run this command. Run it only when the user explicitly asked for ${slash} in this turn — never on your own initiative.`
      : null,
    '',
    '---',
    '',
    body.trim(),
    '',
  ].filter(l => l !== null).join('\n');
}

function readJSON(p) { return JSON.parse(readFileSync(p, 'utf8')); }
function writeText(p, s) { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, s); }
const json = o => JSON.stringify(o, null, 2) + '\n';

/**
 * Generate all agy artifacts under `repoRoot` (the cc-market dir). Returns
 * { files: Map<absPath, content>, remove: absPath[] } and writes them when `write`.
 */
export function generate(repoRoot, { write = true } = {}) {
  const market = readJSON(join(repoRoot, '.claude-plugin', 'marketplace.json'));
  const files = new Map();
  const remove = [];

  for (const entry of market.plugins) {
    const pluginDir = join(repoRoot, entry.name);
    const manifest = readJSON(join(pluginDir, '.claude-plugin', 'plugin.json'));
    if (manifest.name !== entry.name) throw new Error(`${entry.name}: manifest name is ${JSON.stringify(manifest.name)}`);
    const agyManifest = transpileManifest(manifest, entry);

    // Command wrappers.
    const skillsRoot = join(pluginDir, AGY_SKILLS_DIR);
    const existingSkills = existsSync(join(pluginDir, 'skills')) ? new Set(readdirSync(join(pluginDir, 'skills'))) : new Set();
    const wrappers = new Set();
    for (const { full, parts } of commandFiles(pluginDir, manifest)) {
      let skillName = parts.join('-');
      if (existingSkills.has(skillName)) skillName = `${skillName}-command`;
      if (wrappers.has(skillName)) throw new Error(`${entry.name}: duplicate agy command skill ${skillName}`);
      wrappers.add(skillName);
      files.set(join(skillsRoot, skillName, 'SKILL.md'), commandSkill(entry.name, skillName, parts, readFileSync(full, 'utf8')));
    }
    if (wrappers.size) agyManifest.skills = `./${AGY_SKILLS_DIR}/`;
    if (existsSync(skillsRoot)) {
      for (const d of readdirSync(skillsRoot)) if (!wrappers.has(d)) remove.push(join(skillsRoot, d));
    }

    // Agent model-tier transpilation when `claude-agents/` is present.
    const claudeAgentsDir = join(pluginDir, CLAUDE_AGENTS_DIR);
    if (existsSync(claudeAgentsDir) && statSync(claudeAgentsDir).isDirectory()) {
      const srcFiles = readdirSync(claudeAgentsDir).filter(f => f.endsWith('.md')).sort();
      const expectedManifestAgents = srcFiles.map(f => `./${CLAUDE_AGENTS_DIR}/${f}`);
      const declaredAgents = Array.isArray(manifest.agents) ? [...manifest.agents].sort() : [];
      if (JSON.stringify(declaredAgents) !== JSON.stringify(expectedManifestAgents)) {
        throw new Error(
          `${entry.name}: .claude-plugin/plugin.json "agents" must list every file in ${CLAUDE_AGENTS_DIR}/ ` +
          `(expected ${JSON.stringify(expectedManifestAgents)}, got ${JSON.stringify(manifest.agents ?? null)})`
        );
      }
      const agyAgentsDir = join(pluginDir, 'agents');
      const generatedAgents = new Set(srcFiles);
      for (const f of srcFiles) {
        const src = readFileSync(join(claudeAgentsDir, f), 'utf8');
        files.set(join(agyAgentsDir, f), transpileAgent(src, `${entry.name}/${CLAUDE_AGENTS_DIR}/${f}`));
      }
      if (existsSync(agyAgentsDir)) {
        for (const f of readdirSync(agyAgentsDir)) {
          if (!generatedAgents.has(f)) remove.push(join(agyAgentsDir, f));
        }
      }
    }

    files.set(join(pluginDir, '.antigravity-plugin', 'plugin.json'), json(agyManifest));

    const hooksPath = join(pluginDir, 'hooks', 'hooks.json');
    const agyHooks = existsSync(hooksPath) ? transpileHooks(entry.name, readJSON(hooksPath)) : null;
    if (agyHooks) files.set(join(pluginDir, 'hooks.json'), json(agyHooks));
    else remove.push(join(pluginDir, 'hooks.json'));

    const mcpPath = join(pluginDir, '.mcp.json');
    if (existsSync(mcpPath)) files.set(join(pluginDir, 'mcp_config.json'), json(transpileMcp(readJSON(mcpPath))));
    else remove.push(join(pluginDir, 'mcp_config.json'));
  }

  if (write) {
    for (const p of remove) rmSync(p, { recursive: true, force: true });
    for (const [p, s] of files) writeText(p, s);
  }
  return { files, remove: remove.filter(p => existsSync(p)) };
}

if (isMain(import.meta.url)) {
  const repoRoot = process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '..');
  const { files } = generate(repoRoot);
  for (const f of files.keys()) console.log('wrote', relative(repoRoot, f).replaceAll('\\', '/'));
}
